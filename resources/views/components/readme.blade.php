# BladeUI Kit - Job Portal Icons

This package provides a collection of SVG icons as blade components for use in Laravel 12 job portal projects.

## Installation

Icons are already included in the project and are ready to use.

## Basic Usage

Icons can be used in your Blade templates like this:

```blade
<x-icons.briefcase />
```

By default, all icons have a width and height of `1.25rem` (w-5 h-5). You can customize this by passing a `class` attribute:

```blade
<x-icons.briefcase class="w-6 h-6 text-indigo-600-600" />
```

